"""Python binding of frontends/sai_features.c (ctypes). Training computes features with the very C the MCU runs.

A template opts in with a `frontend` block, e.g.
    {"type": "mfcc", "raw_length": 16000, "sample_rate": 16000, "frame": 480, "stride": 320, "n_fft": 512,
     "n_mels": 40, "n_coef": 10, "f_lo": 20, "f_hi": 4000}
    {"type": "band_energy", "raw_length": 256, "n_fft": 256, "bands": 64}
Raw data is [N, C, T]; features come out in the model's input layout [N, C, H, W]:
    band_energy -> [N, C, 1, bands]      (1-D over bands)
    mfcc        -> [N, 1, frames, n_coef] (2-D; channel 0 of the raw data)
"""

from __future__ import annotations

import ctypes
import hashlib
import subprocess
import threading
from pathlib import Path

import numpy as np

from . import config

SRC = config.ROOT / "frontends"
_lib = None
_lock = threading.Lock()


class _Cfg(ctypes.Structure):
    _fields_ = [("sample_rate", ctypes.c_int), ("frame", ctypes.c_int), ("stride", ctypes.c_int),
                ("n_fft", ctypes.c_int), ("n_mels", ctypes.c_int), ("n_coef", ctypes.c_int),
                ("f_lo", ctypes.c_float), ("f_hi", ctypes.c_float)]


WORK = 2 * 1024 + 64


def lib():
    """Build (once per source digest) and load the shared library."""
    global _lib
    with _lock:
        if _lib is None:
            c, h = (SRC / "sai_features.c").read_bytes(), (SRC / "sai_features.h").read_bytes()
            tag = hashlib.sha256(c + h).hexdigest()[:12]
            so = config.DATA_DIR / f"libsai_features_{tag}.so"
            if not so.exists():
                tmp = so.with_suffix(".tmp.so")
                proc = subprocess.run([config.HOST_CC, "-O2", "-std=c11", "-fPIC", "-shared", "-ffp-contract=off",
                                       "-I", str(SRC), str(SRC / "sai_features.c"), "-o", str(tmp), "-lm"],
                                      capture_output=True, text=True)
                if proc.returncode:
                    raise RuntimeError("feature front end build failed: " + proc.stderr[-800:])
                tmp.replace(so)
            L = ctypes.CDLL(str(so))
            fp = ctypes.POINTER(ctypes.c_float)
            L.sai_band_energy.argtypes = [fp, ctypes.c_int, ctypes.c_int, ctypes.c_int, fp, fp]
            L.sai_mfcc.argtypes = [fp, ctypes.c_int, ctypes.POINTER(_Cfg), fp, fp]
            L.sai_mfcc_frames.argtypes = [ctypes.POINTER(_Cfg), ctypes.c_int]
            _lib = L
    return _lib


def _p(a):
    return a.ctypes.data_as(ctypes.POINTER(ctypes.c_float))


def _cfg(fe: dict) -> _Cfg:
    return _Cfg(int(fe["sample_rate"]), int(fe["frame"]), int(fe["stride"]), int(fe["n_fft"]), int(fe["n_mels"]),
                int(fe["n_coef"]), float(fe.get("f_lo", 20.0)), float(fe.get("f_hi", fe["sample_rate"] / 2)))


def output_shape(fe: dict, channels: int) -> tuple[int, int, int]:
    if fe["type"] == "band_energy":
        return channels, 1, int(fe["bands"])
    if fe["type"] == "mfcc":
        frames = lib().sai_mfcc_frames(ctypes.byref(_cfg(fe)), int(fe["raw_length"]))
        return 1, frames, int(fe["n_coef"])
    raise ValueError(f"unknown front end {fe['type']}")


def apply(fe: dict, raw: np.ndarray) -> np.ndarray:
    """raw [N, C, T] (or [N, C, 1, T]) float -> features [N, C, H, W] float32, via the C front end."""
    L = lib()
    raw = np.ascontiguousarray(raw.reshape(raw.shape[0], raw.shape[1], -1), dtype=np.float32)
    n, ch, t = raw.shape
    work = np.zeros(WORK, np.float32)
    if fe["type"] == "band_energy":
        out = np.zeros((n, ch, 1, int(fe["bands"])), np.float32)
        row = np.zeros(int(fe["bands"]), np.float32)
        for i in range(n):
            for c in range(ch):
                x = np.ascontiguousarray(raw[i, c])
                if L.sai_band_energy(_p(x), t, int(fe["n_fft"]), int(fe["bands"]), _p(work), _p(row)):
                    raise ValueError("band_energy: bad arguments (n_fft power of two >= window, bands <= n_fft/2)")
                out[i, c, 0] = row
        return out
    if fe["type"] == "mfcc":
        cfg = _cfg(fe)
        frames = L.sai_mfcc_frames(ctypes.byref(cfg), t)
        out = np.zeros((n, 1, frames, int(fe["n_coef"])), np.float32)
        buf = np.zeros(frames * int(fe["n_coef"]), np.float32)
        for i in range(n):
            x = np.ascontiguousarray(raw[i, 0])
            if L.sai_mfcc(_p(x), t, ctypes.byref(cfg), _p(work), _p(buf)):
                raise ValueError("mfcc: bad arguments")
            out[i, 0] = buf.reshape(frames, -1)
        return out
    raise ValueError(f"unknown front end {fe['type']}")


def config_header(fe: dict) -> str:
    """C header with the exact front-end parameters the model was trained with."""
    lines = ["/* Generated by SAI Platform: feature front end the model was trained with. */",
             "#ifndef SAI_FRONTEND_CONFIG_H", "#define SAI_FRONTEND_CONFIG_H", '#include "sai_features.h"', "",
             f'#define SAI_FRONTEND_TYPE "{fe["type"]}"', f"#define SAI_FRONTEND_RAW_LENGTH {int(fe['raw_length'])}"]
    if fe["type"] == "band_energy":
        lines += [f"#define SAI_FRONTEND_N_FFT {int(fe['n_fft'])}", f"#define SAI_FRONTEND_BANDS {int(fe['bands'])}"]
    else:
        lines += ["static const sai_mfcc_cfg_t sai_frontend_mfcc = {",
                  f"    {int(fe['sample_rate'])}, {int(fe['frame'])}, {int(fe['stride'])}, {int(fe['n_fft'])},"
                  f" {int(fe['n_mels'])}, {int(fe['n_coef'])}, {float(fe.get('f_lo', 20.0))}f,"
                  f" {float(fe.get('f_hi', fe['sample_rate'] / 2))}f", "};"]
    return "\n".join(lines + ["", "#endif", ""])
